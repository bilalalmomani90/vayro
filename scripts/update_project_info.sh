#!/usr/bin/env bash
# يولّد PROJECT_INFO.txt. الاستخدام: update_project_info.sh <BUILD_STATUS> <TEST_STATUS>
# وقت البناء يُكتب فقط عند BUILD_STATUS=SUCCESS (وقت فعلي من الجهاز، لا تخمين).
set -euo pipefail
cd "$(dirname "$0")/.."

BUILD_STATUS="${1:-NOT_BUILT}"
TEST_STATUS="${2:-NOT_RUN}"
VER_NAME=$(grep '^VAYRO_VERSION_NAME=' gradle.properties | cut -d= -f2)
VER_CODE=$(grep '^VAYRO_VERSION_CODE=' gradle.properties | cut -d= -f2)
NOW_TS=$(date '+%Y-%m-%d %H:%M:%S')
NOW_DAY=$(LC_ALL=C date '+%A')
NOW_TZ=$(date '+%Z (UTC%z)')

if [ "$BUILD_STATUS" = "SUCCESS" ]; then
  BUILD_TIME="التاريخ والوقت: $NOW_TS | اليوم: $NOW_DAY | المنطقة الزمنية: $NOW_TZ"
  BUILD_STATE="ناجح"
else
  BUILD_TIME="غير متوفر: لم يُنفَّذ بناء ناجح بعد"
  BUILD_STATE="لم يُنفَّذ (لا يوجد بناء فعلي حتى الآن)"
fi
case "$TEST_STATUS" in
  PASSED) TEST_STATE="ناجحة" ;;
  FAILED) TEST_STATE="فاشلة" ;;
  *)      TEST_STATE="لم تُنفَّذ" ;;
esac

cat > PROJECT_INFO.txt <<INFO
==================================================
VAYRO Browser | فايرو براوزر
==================================================
اسم المشروع (EN): VAYRO Browser
اسم المشروع (AR): فايرو براوزر
الحزمة: com.vayro.browser
رقم الإصدار (Version Name): $VER_NAME
رقم البناء (Version Code): $VER_CODE
تاريخ ووقت البناء الفعلي: $BUILD_TIME
آخر توليد لهذا الملف: $NOW_TS $NOW_TZ

التقنيات المستخدمة:
- Kotlin + Android Gradle Plugin 8.7.3 + Gradle 8.9
- GeckoView (محرك Firefox) عبر BrowserEngine (واجهة مجردة)
- Material Components + ViewBinding
- GitHub Actions للبناء السحابي

الميزات المنفذة (Android):
المرحلة 1:
- هيكل مشروع منظم (core / engine / ui)
- الهوية البصرية والألوان المعتمدة، الوضع الفاتح والداكن (فاتح / داكن / النظام)
- العربية (RTL) والإنجليزية (LTR) مع تبديل اللغة من القائمة
- صفحة رئيسية بسيطة، شريط عنوان وبحث (DuckDuckGo مبدئياً)، فتح، تحديث، شريط تقدم، رجوع
- تشغيل المواقع عبر GeckoView
المرحلة 2 (التبويبات + السجل والمفضلة):
- تبويبات متعددة: فتح/تبديل/إغلاق، عدّاد في الشريط العلوي، نافذة إدارة التبويبات
- تعليق التبويبات غير النشطة، وتحميل كسول للتبويبات المستعادة
- استعادة التبويبات والجلسة بعد إغلاق التطبيق
- سجل التصفح (محلي، SQLite): عرض، حذف عنصر، مسح الكل
- المفضلة (محلية): نجمة في شريط العنوان، عرض، حذف
- تبقى التبويبات حية عند تغيير اللغة أو المظهر
المرحلة 3 (حجب الإعلانات):
- ثلاثة مستويات حماية: عادي / متقدم / أقصى حماية (حماية التتبع في Gecko + قواعد النوافذ والتحويلات)
- حجب الإعلانات والمتتبعات، النوافذ المنبثقة، والتحويلات التلقائية المريبة (أقصى حماية، قاعدة استدلالية)
- إضافة تنظيف مدمجة (CSS) تخفي الفراغات الإعلانية في المتقدم والأقصى
- حماية مستقلة لكل موقع (تعطيل الحماية، السماح بالنوافذ) + سماح مؤقت للتحويل المحجوب
- سجل الحجب وتقرير يومي/أسبوعي مع سبب كل حجب (من بيانات فعلية فقط)
المرحلة 4 (الخصوصية):
- سياسة الكوكيز (السماح للكل / حجب المتتبعات / حجب الطرف الثالث)
- مسح سجل التصفح ومسح بيانات المواقع (بتأكيد)
- أذونات الكاميرا والميكروفون والموقع بحوار صريح عند كل طلب؛ الإشعارات تُرفض (غير مدعومة بعد)
- السجل المحلي لا يرسل أي بيانات خارج الجهاز
المرحلة 5 (مدير التنزيلات):
- قائمة تنزيلات حية: الحجم، السرعة، التقدم، إيقاف مؤقت واستكمال (إن دعمه الخادم)، إعادة المحاولة، إلغاء
- بحث وتصنيف (مستندات/صور/فيديو/صوت/أرشيف/تطبيقات/أخرى) وحفظ منظم في Download/VAYRO/<التصنيف>
- تحذير قبل تنزيل أو فتح الملفات التنفيذية والمقنَّعة (مثل invoice.pdf.exe)
- فتح الملف بعد التنزيل، وخدمة أمامية تبقي التنزيل حياً مع إشعار
- الحد الأدنى لنظام Android صار 10 (API 29)
المرحلة 6 (توفير البيانات):
- ثلاثة أوضاع: إيقاف / قياسي (منع التشغيل التلقائي للوسائط) / صارم (مع عدم تحميل الصور)
- استثناء لكل موقع لإبقاء الصور
المرحلة 9 (أساسيات التصفح):
- فتح روابط http/https من التطبيقات الأخرى، واستقبال الروابط من المشاركة، وخيار المتصفح الافتراضي
- مشاركة الصفحة، التقدّم للأمام
- اقتراحات العنوان من المفضلة والسجل المحليين فقط (بلا إرسال لأي خادم)
المرحلة 10 (التصفح الخاص):
- تبويبات خاصة: جلسة Gecko معزولة، بلا سجل ولا حفظ للجلسة ولا تسجيل للحجب، ومنع لقطات الشاشة
- إغلاق كل التبويبات الخاصة من القائمة
المرحلة 14 (الترجمة المحلية):
- ترجمة الصفحة كاملة داخل الجهاز عبر محرك الترجمة في GeckoView، إلى لغة التطبيق الحالية، مع «عرض الأصل»
- اكتشاف لغة الصفحة؛ نموذج اللغة يُنزَّل مرة واحدة بعد موافقة صريحة تعرض حجمه
- نص الصفحة لا يُرسل لأي خادم. غير منفّذ بعد: ترجمة النص المحدد، الكلمات، الصور/PDF، القاموس
المرحلة 13 (التشخيص واستعادة الانهيارات):
- «حول التطبيق والتشخيص» في القائمة: الإصدار، GeckoView، الجهاز، الأعداد (بلا روابط)، مع مشاركة بقرار المستخدم
- حفظ تقرير الانهيار محلياً وعرضه في التشغيل التالي (لا يُرسل تلقائياً أبداً)
- استعادة التبويب الذي تنهار عملية المحتوى فيه بإعادة فتح صفحته (حتى 3 محاولات)
المرحلة 11 (الفيديو):
- دعم ملء الشاشة للفيديو (إخفاء الأشرطة، منع انطفاء الشاشة، زر الرجوع يخرج منه)
- الصورة داخل الصورة عند الضغط على زر الرئيسية أثناء فيديو بملء الشاشة
المرحلة 12 (المواقع كتطبيقات):
- إضافة أي موقع إلى الشاشة الرئيسية كاختصار بأيقونة حرفية يفتحه داخل VAYRO
المرحلة 7 (الصفحة الرئيسية القابلة للتخصيص):
- أقسام: الاختصارات، مجموعات المواقع، المفضلة، الأحدث؛ ترتيبها وإظهارها وإخفاؤها
- حجم البطاقات (مضغوط/عادي/كبير)، خلفيات جاهزة، إظهار/إخفاء زر التحديث ونجمة المفضلة
- إضافة اختصارات يدوياً أو من الصفحة الحالية
المرحلة 8 (مساحات العمل ومجموعات المواقع):
- مساحات عمل بأسماء وأيقونات؛ لكل مساحة تبويباتها ومفضلتها واختصاراتها ومجموعاتها
- تبديل المساحة يحفظ القديمة ويحرر ذاكرتها
- مجموعات مواقع: إنشاء/تعديل/حذف، وفتح المجموعة كلها بضغطة واحدة (تحميل كسول للتبويبات)
- عرض البيانات المستهلكة فعلياً (اليوم وآخر 7 أيام) من عدّاد النظام؛ لا يوجد تقدير للبيانات الموفرة لأنه غير قابل للقياس

حالة البناء: $BUILD_STATE
حالة الاختبارات: $TEST_STATE

ملاحظة: لا يحدَّث وقت البناء إلا بعد بناء ناجح فعلي (CI أو جهاز المطوّر).
INFO
echo "PROJECT_INFO.txt updated (build=$BUILD_STATUS tests=$TEST_STATUS)"
